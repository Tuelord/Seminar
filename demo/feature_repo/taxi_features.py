"""
feature_repo/taxi_features.py
------------------------------
Feast feature definitions for the taxi trip demo.
Maps to the Parquet file generated by generate_features.py.
"""

import os
from datetime import timedelta

from feast import Entity, FeatureView, FileSource, Field
from feast.types import Float64, Int64

# ── Paths (absolute, so Feast works regardless of cwd) ───────────────────────
_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
_DEMO_DIR = os.path.dirname(_THIS_DIR)
_DATA_DIR = os.path.join(_DEMO_DIR, "data")

# ── Data source ──────────────────────────────────────────────────────────────
taxi_source = FileSource(
    path=os.path.join(_DATA_DIR, "taxi_features.parquet"),
    timestamp_field="event_timestamp",
)

# ── Entity ───────────────────────────────────────────────────────────────────
trip = Entity(
    name="trip_id",
    description="Unique identifier for each taxi trip",
)

# ── Feature View ─────────────────────────────────────────────────────────────
trip_features = FeatureView(
    name="trip_features",
    entities=[trip],
    ttl=timedelta(days=365),
    schema=[
        Field(name="trip_distance",  dtype=Float64),
        Field(name="pickup_hour",    dtype=Int64),
        Field(name="pickup_weekday", dtype=Int64),
        Field(name="passenger_count", dtype=Int64),
    ],
    source=taxi_source,
    online=True,
)
